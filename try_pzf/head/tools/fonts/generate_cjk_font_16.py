"""Generate the task-guide's compact OFL Chinese bitmap subset (requires Pillow).

Usage: python generate_cjk_font_16.py --font C:/Windows/Fonts/NotoSansSC-VF.ttf
No Windows proprietary glyphs are used. The input must be Noto Sans SC;
see README.md and OFL-NotoSansSC.txt for provenance and redistribution terms.
"""
from __future__ import annotations

import argparse
import hashlib
from pathlib import Path
import struct

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[2]
EXTRAS = "三步任务点击开始每步分钟第步点击退出本轮引导结束暂时没收到结果再说一次试试丢掉桌面垃圾把物品分类放好擦净桌面并摆回常用品，。！？：；、（）—…①②③"


def font_metadata(path: Path) -> tuple[str, str]:
    """Read sfnt name entries without a fontTools build-time dependency."""
    data = path.read_bytes()
    count = struct.unpack_from(">H", data, 4)[0]
    offset = None
    for i in range(count):
        tag, _, off, _ = struct.unpack_from(">4sIII", data, 12 + i * 16)
        if tag == b"name":
            offset = off
            break
    assert offset is not None, "Missing font name table"
    _, count, string_offset = struct.unpack_from(">HHH", data, offset)
    names = {}
    for i in range(count):
        platform, _, _, name_id, length, off = struct.unpack_from(">HHHHHH", data, offset + 6 + i * 12)
        start = offset + string_offset + off
        text = data[start:start + length].decode("utf-16-be" if platform in (0, 3) else "latin1")
        names.setdefault(name_id, text)
    assert "Noto Sans SC" in names.get(1, ""), "Expected open-licensed Noto Sans SC"
    assert "Open Font License" in names.get(13, ""), "Input must retain its OFL license metadata"
    return names.get(0, ""), names.get(13, "")


def codepoints() -> list[int]:
    chars = set(chr(c) for c in range(32, 127)) | set(EXTRAS)
    for lead in range(0xB0, 0xD8):
        for trail in range(0xA1, 0xFF):
            try:
                chars.add(bytes((lead, trail)).decode("gb2312"))
            except UnicodeDecodeError:
                pass
    return sorted(ord(c) for c in chars)


def make_rows(font: ImageFont.FreeTypeFont, cp: int) -> list[int]:
    image = Image.new("L", (16, 20))
    draw = ImageDraw.Draw(image)
    char = chr(cp)
    draw.text((0, 14), char, font=font, fill=255, anchor="ls", stroke_width=0)
    # ASCII is 8px wide; fit the glyph including side bearings into its cell.
    if cp < 128 and cp != 32:
        bbox = image.getbbox()
        if bbox:
            crop = image.crop(bbox)
            crop = crop.resize((min(8, crop.width), crop.height), Image.Resampling.LANCZOS)
            image = Image.new("L", (16, 20))
            image.paste(crop, (0, bbox[1]))
    return [sum((1 << (15 - x)) for x in range(16) if image.getpixel((x, y)) >= 96) for y in range(16)]


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--font", type=Path, required=True)
    parser.add_argument("--preview", type=Path)
    args = parser.parse_args()
    copyright_text, _ = font_metadata(args.font)
    font = ImageFont.truetype(str(args.font), 16)
    font.set_variation_by_name("Regular")
    cps = codepoints()
    rows = [make_rows(font, cp) for cp in cps]
    assert len(cps) >= 3850
    assert all(any(r) or cp == 32 for cp, r in zip(cps, rows)), "Blank non-space glyph"
    digest = hashlib.sha256(args.font.read_bytes()).hexdigest()
    out = ROOT / "main/display/cjk_font_16_data.inc"
    lines = [
        "/* Generated by tools/fonts/generate_cjk_font_16.py. Do not hand edit.",
        " * Font data license: SIL Open Font License, Version 1.1 (OFL-1.1).",
        f" * {copyright_text}",
        " * Derivative name: Focus Task CJK16. See tools/fonts/OFL-NotoSansSC.txt.",
        f" * Input SHA256: {digest}",
        f" * {len(cps)} glyphs, {len(cps) * 34} bytes (16x16 rows + uint16 Unicode index). */",
        "static const uint16_t s_cjk16_codepoints[] = {",
    ]
    for i in range(0, len(cps), 12):
        lines.append("    " + ", ".join(f"0x{cp:04X}" for cp in cps[i:i + 12]) + ",")
    lines.extend(["};", "static const uint16_t s_cjk16_rows[][16] = {"])
    for cp, bitmap in zip(cps, rows):
        lines.append("    {" + ",".join(f"0x{r:04X}" for r in bitmap) + f"}}, /* U+{cp:04X} */")
    lines.append("};\n")
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"Generated {out}: {len(cps)} glyphs, {len(cps) * 34:,} binary bytes")
    if args.preview:
        preview = Image.new("RGB", (480, 480), "black")
        draw = ImageDraw.Draw(preview)
        mapping = dict(zip(cps, rows))
        for y, text in [(70, "三步任务"), (140, "1 丢掉桌面垃圾"), (200, "2 把物品分类放好"),
                        (260, "3 擦净桌面并摆回常用品"), (380, "点击开始，每步3分钟")]:
            x = (480 - sum(8 if ord(c) < 128 else 16 for c in text)) // 2
            for c in text:
                for gy, bits in enumerate(mapping[ord(c)]):
                    for gx in range(16):
                        if bits & (0x8000 >> gx):
                            draw.point((x + gx, y + gy), fill=(225, 239, 215))
                x += 8 if ord(c) < 128 else 16
        preview.save(args.preview)


if __name__ == "__main__":
    main()
